def build_bosses():
    assert set(SHAPES) == {row[0] for row in EGYPTIAN_BOSSES}
    for number, asset, *_ in EGYPTIAN_BOSSES:
        body = SHAPES[number]
        svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 240 240">'
               '<g fill="#535b83" stroke="#c69ce9" stroke-width="3" '
               'stroke-linejoin="round" stroke-linecap="round">'+body+'</g></svg>')
        (ART/(asset+'.svg')).write_text(svg, encoding='utf-8')
    build(characters={row[1] for row in EGYPTIAN_BOSSES})
    print('20 Egyptian boss portraits; original portraits untouched.')


